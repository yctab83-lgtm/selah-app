// Helper: Intelligent search matching verses by query and/or prayer context
export function searchBibleVault(
  query: string,
  options?: {
    prayerContext?: {
      title?: string;
      request?: string;
      category?: string;
    };
    theme?: string;
    translation?: string;
  }
): { verse: BibleVaultVerse; score: number; matchReasons: string[] }[] {
  const cleanQ = (query || '').toLowerCase().trim();
  const searchWords = cleanQ ? cleanQ.split(/\s+/).filter(Boolean) : [];

  // Extract keywords from prayer text if provided
  const prayerWords: string[] = [];
  if (options?.prayerContext) {
    const raw = `${options.prayerContext.title || ''} ${options.prayerContext.request || ''} ${options.prayerContext.category || ''}`.toLowerCase();
    const tokens = raw.replace(/[^\w\s\u00C0-\u017F]/g, ' ').split(/\s+/).filter((w) => w.length > 2);
    prayerWords.push(...tokens);
  }

  const results = COMPREHENSIVE_BIBLE_VAULT.map((verse) => {
    let score = 0;
    const matchReasons: string[] = [];

    // Theme filter
    if (options?.theme && options.theme !== 'Alle' && verse.theme !== options.theme) {
      return { verse, score: -1, matchReasons };
    }

    // Translation filter
    if (options?.translation && options.translation !== 'Alle' && !verse.translation.includes(options.translation)) {
      return { verse, score: -1, matchReasons };
    }

    const fullVerseText = `${verse.reference} ${verse.book} ${verse.text} ${verse.theme} ${(verse.keywords || []).join(' ')}`.toLowerCase();

    // 1. Explicit search query matching
    if (searchWords.length > 0) {
      let matchesAll = true;
      for (const word of searchWords) {
        if (fullVerseText.includes(word)) {
          if (verse.text.toLowerCase().includes(word)) {
            score += 15;
            matchReasons.push(`Woord in teks: "${word}"`);
          } else if (verse.reference.toLowerCase().includes(word) || verse.book.toLowerCase().includes(word)) {
            score += 25;
            matchReasons.push(`Boek/verwysing: "${word}"`);
          } else {
            score += 10;
            matchReasons.push(`Tema/sleutelwoord: "${word}"`);
          }
        } else {
          matchesAll = false;
        }
      }
      if (!matchesAll) {
        score = 0; // Must match search words if provided
      }
    } else {
      // Default baseline score if no query specified
      score = 5;
    }

    // 2. Prayer context relevance matching (when opening from "Teken nuwe gebed aan")
    if (options?.prayerContext && prayerWords.length > 0 && score >= 0) {
      let prayerMatches = 0;
      for (const pWord of prayerWords) {
        // Skip common stop words
        if (['van', 'die', 'vir', 'dat', 'wat', 'om', 'ons', 'ek', 'het', 'nie', 'sal', 'aan', 'ook', 'met', 'maar', 'hierdie'].includes(pWord)) {
          continue;
        }

        if (fullVerseText.includes(pWord)) {
          prayerMatches++;
          score += 12;
          if (matchReasons.length < 3) {
            matchReasons.push(`Pas by jou gebed: "${pWord}"`);
          }
        }
      }

      // Semantic category boost
      const cat = (options.prayerContext.category || '').toLowerCase();
      if (cat.includes('genees') && (verse.theme.toLowerCase().includes('genees') || fullVerseText.includes('siek'))) {
        score += 25;
        matchReasons.push('Direk van toepassing op Genesing');
      } else if (cat.includes('dank') && (verse.theme.toLowerCase().includes('dank') || fullVerseText.includes('lof'))) {
        score += 25;
        matchReasons.push('Direk van toepassing op Danksegging');
      } else if (cat.includes('familie') && (fullVerseText.includes('huis') || fullVerseText.includes('kind'))) {
        score += 25;
        matchReasons.push('Direk van toepassing op Familie');
      }
    }

    return { verse, score, matchReasons };
  });

  return results
    .filter((r) => r.score > 0)
    .sort((a, b) => b.score - a.score);
}
